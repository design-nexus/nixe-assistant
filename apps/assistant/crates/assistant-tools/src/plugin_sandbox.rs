//! Plugin sandboxes. Each plugin runs in bubblewrap with only what its manifest's `[sandbox]`
//! declares (`SandboxProfile`), under a seccomp filter, in a systemd scope with memory, task
//! and CPU limits. No `[sandbox]` means the strictest: no network, an empty HOME but for the
//! plugin's own package (read-only) and data folder, no desktop sockets.
//!
//! Session-bus access goes through `xdg-dbus-proxy`, which lets the plugin call only the
//! names it declares. Wayland, PipeWire, Hyprland and the system bus are the real sockets.
//! A first-party plugin that has to start programs on the desktop (apps, terminals, pkexec)
//! may be `unconfined`: it keeps the limits but not bubblewrap or seccomp.

use crate::fs::{SECRET, SELF};
use anyhow::{Context, Result};
use assistant_core::config::{HomeAccess, SandboxDevice, SandboxProfile, SandboxSocket};
use std::collections::HashMap;
use std::os::fd::{AsRawFd, FromRawFd, OwnedFd, RawFd};
use std::path::{Component, Path, PathBuf};

/// The plugin being started.
pub struct Launch<'a> {
    pub id: &'a str,
    pub executable: &'a str,
    pub args: &'a [String],
    pub env: &'a HashMap<String, String>,
    pub package: &'a Path,
    pub data: &'a Path,
    /// Bundled with the assistant or generated by it (`bundled`, `migrated`).
    pub first_party: bool,
}

/// A command ready to spawn, and what must live as long as it.
pub struct Prepared {
    pub command: tokio::process::Command,
    /// The session-bus proxy, stopped with the plugin.
    pub proxy: Option<tokio::process::Child>,
    /// Descriptors the child inherits (seccomp program, proxy sync); closed in the daemon
    /// once the child has started.
    pub fds: Vec<OwnedFd>,
}

const DEFAULT_MEMORY_MB: u64 = 1024;
const DEFAULT_TASKS: u64 = 256;
const DEFAULT_CPU_PERCENT: u64 = 200;
const UNCONFINED_MEMORY_MB: u64 = 8192;
const UNCONFINED_TASKS: u64 = 4096;

/// Checks a profile before anything starts.
pub fn validate(profile: &SandboxProfile) -> Result<()> {
    for p in profile.read.iter().chain(&profile.write) {
        anyhow::ensure!(
            (p.starts_with("~/") || p.starts_with('/')) && !Path::new(p).components().any(|c| c == Component::ParentDir) && !p.contains('\0'),
            "sandbox path {p:?} must be absolute or start with ~/, without .."
        );
    }
    for name in &profile.talk {
        anyhow::ensure!(
            !name.is_empty() && name.len() <= 255 && name.contains('.') && name.chars().all(|c| c.is_ascii_alphanumeric() || "._-*".contains(c)) && name.find('*').is_none_or(|i| i == name.len() - 1),
            "invalid session-bus name {name:?}"
        );
    }
    anyhow::ensure!(
        profile.talk.is_empty() || profile.sockets.contains(&SandboxSocket::SessionBus),
        "talk needs sockets = [\"session-bus\"]"
    );
    anyhow::ensure!(
        !profile.sockets.contains(&SandboxSocket::Systemd) || profile.host_processes,
        "the systemd socket needs host_processes (the manager checks the caller's process)"
    );
    anyhow::ensure!(profile.memory_mb.is_none_or(|m| (64..=32768).contains(&m)), "memory_mb must be 64 to 32768");
    anyhow::ensure!(profile.tasks.is_none_or(|t| (8..=16384).contains(&t)), "tasks must be 8 to 16384");
    anyhow::ensure!(profile.cpu_percent.is_none_or(|c| (10..=3200).contains(&c)), "cpu_percent must be 10 to 3200");
    anyhow::ensure!(profile.unconfined.as_ref().is_none_or(|r| !r.trim().is_empty()), "unconfined needs a reason");
    Ok(())
}

/// One line for people: what the plugin can reach.
pub fn summary(profile: &SandboxProfile) -> String {
    if let Some(reason) = &profile.unconfined {
        return format!("unconfined: {reason}");
    }
    let mut parts = vec![match profile.home {
        HomeAccess::None => "no home folder".to_string(),
        HomeAccess::Read => "reads the home folder".to_string(),
        HomeAccess::Write => "writes the home folder".to_string(),
    }];
    if profile.network {
        parts.push("network".into());
    }
    for s in &profile.sockets {
        parts.push(match s {
            SandboxSocket::Wayland => "Wayland".into(),
            SandboxSocket::Pipewire => "PipeWire".into(),
            SandboxSocket::Hyprland => "Hyprland (can start programs)".into(),
            SandboxSocket::SessionBus => format!("session bus: {}", profile.talk.join(", ")),
            SandboxSocket::SystemBus => "system bus".into(),
            SandboxSocket::Systemd => "user services".into(),
        });
    }
    parts.join(", ")
}

fn expand(home: &Path, p: &str) -> PathBuf {
    match p.strip_prefix("~/") {
        Some(rest) => home.join(rest),
        None => PathBuf::from(p),
    }
}

fn under_any(home: &Path, path: &Path, list: &[&str]) -> bool {
    list.iter().any(|d| path.starts_with(home.join(d)))
}

/// Folders under HOME that hold `path`'s code: the nearest ancestor with a package file,
/// else its folder. For servers adopted from the configuration (a Node script and its
/// `node_modules`, a binary under `~/.local/share`).
pub fn code_folder(home: &Path, path: &Path) -> Option<PathBuf> {
    let path = path.canonicalize().ok()?;
    if !path.starts_with(home) || path == home {
        return None;
    }
    let markers = ["package.json", "pyproject.toml", "Cargo.toml", "plugin.toml"];
    let found = path
        .ancestors()
        .skip(1)
        .take_while(|d| d.starts_with(home) && *d != home)
        .find(|d| markers.iter().any(|m| d.join(m).is_file()));
    if let Some(found) = found {
        return Some(found.to_path_buf());
    }
    let dir = path.parent().filter(|p| *p != home)?;
    // A program in an install's bin folder (mise, fnm, pyenv) needs the rest of the install
    // (Python's standard library): bind the prefix, unless it holds secrets (~/.local does).
    let prefix = dir.parent().filter(|p| dir.file_name().is_some_and(|n| n == "bin") && p.starts_with(home) && *p != home);
    match prefix {
        Some(prefix) if !SECRET.iter().any(|s| home.join(s).starts_with(prefix)) => Some(prefix.to_path_buf()),
        _ => Some(dir.to_path_buf()),
    }
}

/// The bubblewrap arguments, without the seccomp and sync descriptors. `runtime` is
/// `XDG_RUNTIME_DIR`; `bus` the proxy's socket when the plugin talks on the session bus.
pub fn bwrap_args(profile: &SandboxProfile, launch: &Launch, home: &Path, runtime: Option<&Path>, bus: Option<&Path>) -> Result<Vec<String>> {
    let mut a: Vec<String> = Vec::new();
    let mut push = |items: &[&str]| a.extend(items.iter().map(|s| s.to_string()));
    push(&["--die-with-parent", "--new-session", "--unshare-user", "--unshare-ipc", "--unshare-uts", "--unshare-cgroup-try"]);
    if !profile.host_processes {
        push(&["--unshare-pid"]);
    }
    if !profile.network {
        push(&["--unshare-net"]);
    }
    push(&["--ro-bind", "/usr", "/usr", "--ro-bind", "/etc", "/etc", "--ro-bind-try", "/opt", "/opt", "--ro-bind", "/sys", "/sys"]);
    for dir in ["/bin", "/lib", "/lib64", "/sbin"] {
        match std::fs::read_link(dir) {
            Ok(target) => push(&["--symlink", &target.display().to_string(), dir]),
            Err(_) if Path::new(dir).exists() => push(&["--ro-bind", dir, dir]),
            Err(_) => {}
        }
    }
    push(&["--proc", "/proc", "--dev", "/dev", "--tmpfs", "/tmp"]);
    if profile.devices.contains(&SandboxDevice::Gpu) {
        for dev in ["/dev/nvidiactl", "/dev/nvidia0", "/dev/nvidia-uvm", "/dev/nvidia-uvm-tools", "/dev/nvidia-modeset", "/dev/dri"] {
            push(&["--dev-bind-try", dev, dev]);
        }
    }
    if profile.network {
        // /etc/resolv.conf usually points into systemd-resolved's runtime folder.
        push(&["--ro-bind-try", "/run/systemd/resolve", "/run/systemd/resolve"]);
    }
    let home_s = home.display().to_string();
    match profile.home {
        HomeAccess::None => push(&["--tmpfs", &home_s]),
        HomeAccess::Read => push(&["--ro-bind", &home_s, &home_s]),
        HomeAccess::Write => push(&["--bind", &home_s, &home_s]),
    }
    if profile.home != HomeAccess::None {
        for d in SECRET {
            let p = home.join(d);
            if p.is_dir() {
                push(&["--tmpfs", &p.display().to_string()]);
            }
        }
    }
    if profile.home == HomeAccess::Write {
        // The assistant's own folders stay read-only; the file tools' backups don't.
        for d in SELF {
            let p = home.join(d).display().to_string();
            push(&["--ro-bind-try", &p, &p]);
        }
        let backups = home.join(".local/state/nixe-assistant/file-backups").display().to_string();
        push(&["--bind-try", &backups, &backups]);
    }
    for (paths, writable) in [(&profile.read, false), (&profile.write, true)] {
        for p in paths {
            let path = expand(home, p);
            anyhow::ensure!(!under_any(home, &path, SECRET), "{p} holds secrets; a plugin can't have it");
            anyhow::ensure!(!writable || !under_any(home, &path, SELF), "{p} is the assistant's own; a plugin can't write it");
            let s = path.display().to_string();
            push(&[if writable { "--bind-try" } else { "--ro-bind-try" }, &s, &s]);
        }
    }
    // The executable and its script, when they live under HOME.
    for p in std::iter::once(launch.executable).chain(launch.args.iter().map(String::as_str)) {
        if let Some(dir) = Path::new(p).is_absolute().then(|| code_folder(home, Path::new(p))).flatten() {
            if !under_any(home, &dir, SECRET) {
                let s = dir.display().to_string();
                push(&["--ro-bind-try", &s, &s]);
            }
        }
    }
    let package = launch.package.display().to_string();
    push(&["--ro-bind", &package, &package]);
    let data = launch.data.display().to_string();
    push(&["--bind", &data, &data]);
    if let (Some(runtime), false) = (runtime, profile.sockets.is_empty()) {
        let r = runtime.display().to_string();
        push(&["--perms", "0700", "--dir", &r]);
        for s in &profile.sockets {
            match s {
                SandboxSocket::Wayland => {
                    let display = std::env::var("WAYLAND_DISPLAY").unwrap_or_else(|_| "wayland-0".into());
                    let p = runtime.join(&display).display().to_string();
                    push(&["--bind-try", &p, &p]);
                }
                SandboxSocket::Pipewire => {
                    let p = runtime.join("pipewire-0").display().to_string();
                    push(&["--bind-try", &p, &p]);
                }
                SandboxSocket::Hyprland => {
                    let p = runtime.join("hypr").display().to_string();
                    push(&["--bind-try", &p, &p]);
                }
                SandboxSocket::SessionBus => {
                    let proxy = bus.context("the session-bus proxy isn't running")?.display().to_string();
                    let inside = runtime.join("bus").display().to_string();
                    push(&["--bind", &proxy, &inside]);
                }
                SandboxSocket::SystemBus => push(&["--bind-try", "/run/dbus/system_bus_socket", "/run/dbus/system_bus_socket"]),
                SandboxSocket::Systemd => {
                    let p = runtime.join("systemd/private").display().to_string();
                    push(&["--bind-try", &p, &p]);
                }
            }
        }
    }
    push(&["--chdir", &package, "--clearenv"]);
    let path = std::env::var("PATH").unwrap_or_else(|_| "/usr/local/bin:/usr/bin".into());
    push(&["--setenv", "PATH", &path, "--setenv", "HOME", &home_s, "--setenv", "TERM", "dumb", "--setenv", "PYTHONDONTWRITEBYTECODE", "1"]);
    for var in ["LANG", "LC_ALL", "TZ"] {
        if let Ok(v) = std::env::var(var) {
            push(&["--setenv", var, &v]);
        }
    }
    if let (Some(runtime), false) = (runtime, profile.sockets.is_empty()) {
        let r = runtime.display().to_string();
        push(&["--setenv", "XDG_RUNTIME_DIR", &r]);
        if profile.sockets.contains(&SandboxSocket::Wayland) {
            if let Ok(v) = std::env::var("WAYLAND_DISPLAY") {
                push(&["--setenv", "WAYLAND_DISPLAY", &v]);
            }
        }
        if profile.sockets.contains(&SandboxSocket::Hyprland) {
            if let Ok(v) = std::env::var("HYPRLAND_INSTANCE_SIGNATURE") {
                push(&["--setenv", "HYPRLAND_INSTANCE_SIGNATURE", &v]);
            }
        }
        if profile.sockets.contains(&SandboxSocket::SessionBus) {
            let address = format!("unix:path={}", runtime.join("bus").display());
            push(&["--setenv", "DBUS_SESSION_BUS_ADDRESS", &address]);
        }
    }
    let mut env: Vec<_> = launch.env.iter().collect();
    env.sort();
    for (k, v) in env {
        push(&["--setenv", k, v]);
    }
    Ok(a)
}

/// `systemd-run --user --scope` with the profile's limits, or nothing when the user's
/// service manager can't make scopes (checked once).
pub fn limits(profile: &SandboxProfile, unit: &str) -> Vec<String> {
    static AVAILABLE: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    let available = *AVAILABLE.get_or_init(|| {
        let ok = std::process::Command::new("systemd-run")
            .args(["--user", "--scope", "--quiet", "--collect", "true"])
            .stdin(std::process::Stdio::null())
            .stdout(std::process::Stdio::null())
            .stderr(std::process::Stdio::null())
            .status()
            .is_ok_and(|s| s.success());
        if !ok {
            tracing::warn!("systemd-run --user --scope is unavailable: plugins run without memory, task and CPU limits");
        }
        ok
    });
    if !available {
        return Vec::new();
    }
    limits_args(profile, unit)
}

fn limits_args(profile: &SandboxProfile, unit: &str) -> Vec<String> {
    let unconfined = profile.unconfined.is_some();
    let memory = profile.memory_mb.unwrap_or(if unconfined { UNCONFINED_MEMORY_MB } else { DEFAULT_MEMORY_MB });
    let tasks = profile.tasks.unwrap_or(if unconfined { UNCONFINED_TASKS } else { DEFAULT_TASKS });
    let mut a: Vec<String> = ["systemd-run", "--user", "--scope", "--quiet", "--collect", "--unit", unit].map(String::from).to_vec();
    a.extend(["-p".into(), format!("MemoryMax={memory}M"), "-p".into(), format!("TasksMax={tasks}")]);
    if let Some(cpu) = profile.cpu_percent.or((!unconfined).then_some(DEFAULT_CPU_PERCENT)) {
        a.extend(["-p".into(), format!("CPUQuota={cpu}%")]);
    }
    a.push("--".into());
    a
}

fn unit_name(id: &str) -> String {
    static N: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
    let n = N.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    format!("nixe-assistant-plugin-{id}-{}-{n}.scope", std::process::id())
}

/// The command that starts `launch` inside its sandbox.
pub async fn prepare(profile: &SandboxProfile, launch: &Launch<'_>) -> Result<Prepared> {
    validate(profile)?;
    let limits = limits(profile, &unit_name(launch.id));
    if profile.unconfined.is_some() {
        anyhow::ensure!(launch.first_party, "only first-party plugins may run unconfined");
        let mut argv = limits;
        argv.push(launch.executable.into());
        argv.extend(launch.args.iter().cloned());
        let mut command = tokio::process::Command::new(&argv[0]);
        command.args(&argv[1..]).envs(launch.env);
        return Ok(Prepared { command, proxy: None, fds: Vec::new() });
    }
    let home = crate::fs::home()?;
    // A bare command name is looked up now: inside, `~/.local/bin` and the like aren't there.
    // Links are followed so the real program's folder is the one bound.
    let executable = resolve(launch.executable).with_context(|| format!("{} not found", launch.executable))?;
    let executable = executable.display().to_string();
    let launch = &Launch { executable: &executable, ..*launch };
    let runtime = std::env::var_os("XDG_RUNTIME_DIR").map(PathBuf::from);
    let mut fds = Vec::new();
    let mut proxy = None;
    let mut bus = None;
    if profile.sockets.contains(&SandboxSocket::SessionBus) {
        let (child, socket, sync) = start_proxy(launch.id, &profile.talk, runtime.as_deref()).await?;
        proxy = Some(child);
        bus = Some(socket);
        fds.push(sync);
    }
    let mut argv = limits;
    argv.push("bwrap".into());
    argv.extend(bwrap_args(profile, launch, &home, runtime.as_deref(), bus.as_deref())?);
    let seccomp = seccomp_fd()?;
    argv.extend(["--seccomp".into(), seccomp.as_raw_fd().to_string()]);
    if let Some(sync) = fds.first() {
        // bwrap holds it while the sandbox lives; the proxy stops when it closes.
        argv.extend(["--sync-fd".into(), sync.as_raw_fd().to_string()]);
    }
    fds.push(seccomp);
    argv.push("--".into());
    argv.push(launch.executable.into());
    argv.extend(launch.args.iter().cloned());
    let mut command = tokio::process::Command::new(&argv[0]);
    command.args(&argv[1..]);
    inherit(&mut command, fds.iter().map(AsRawFd::as_raw_fd).collect());
    Ok(Prepared { command, proxy, fds })
}

fn resolve(program: &str) -> Option<PathBuf> {
    let found = if program.contains('/') {
        Some(PathBuf::from(program))
    } else {
        std::env::split_paths(&std::env::var_os("PATH")?).map(|d| d.join(program)).find(|p| p.is_file())
    };
    let path = found?.canonicalize().ok()?;
    Some(exec_target(&path).unwrap_or(path))
}

/// The program a one-line `exec /path/to/program "$@"` wrapper runs (install.sh writes
/// `nixe-assistant-node` this way), so the sandbox binds that program, not the wrapper's folder.
fn exec_target(path: &Path) -> Option<PathBuf> {
    if std::fs::metadata(path).ok()?.len() > 4096 {
        return None;
    }
    let text = std::fs::read_to_string(path).ok()?;
    if !text.starts_with("#!") {
        return None;
    }
    let target = text.lines().find_map(|l| l.trim().strip_prefix("exec ")?.strip_suffix(" \"$@\"").map(str::trim).map(String::from))?;
    let target = PathBuf::from(target.trim_matches(['\'', '"']));
    (target.is_absolute() && target.is_file()).then(|| target.canonicalize().ok()).flatten()
}

/// Lets the child keep `fds` across exec (they're close-on-exec in the daemon).
pub fn inherit(command: &mut tokio::process::Command, fds: Vec<RawFd>) {
    unsafe {
        command.pre_exec(move || {
            for fd in &fds {
                if libc::fcntl(*fd, libc::F_SETFD, 0) != 0 {
                    return Err(std::io::Error::last_os_error());
                }
            }
            Ok(())
        });
    }
}

/// `xdg-dbus-proxy` for one plugin: only the declared names can be called. Returns the
/// proxy, its socket and the descriptor that keeps it running (handed to bwrap).
async fn start_proxy(id: &str, talk: &[String], runtime: Option<&Path>) -> Result<(tokio::process::Child, PathBuf, OwnedFd)> {
    let address = std::env::var("DBUS_SESSION_BUS_ADDRESS").context("no session bus")?;
    let dir = runtime.context("no XDG_RUNTIME_DIR")?.join("nixe-assistant").join("dbus-proxy");
    std::fs::create_dir_all(&dir)?;
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(&dir, std::fs::Permissions::from_mode(0o700))?;
    }
    static N: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
    let socket = dir.join(format!("{id}-{}-{}", std::process::id(), N.fetch_add(1, std::sync::atomic::Ordering::Relaxed)));
    let _ = std::fs::remove_file(&socket);
    let (read, write) = pipe()?;
    let mut command = tokio::process::Command::new("xdg-dbus-proxy");
    command
        .arg(format!("--fd={}", write.as_raw_fd()))
        .arg(&address)
        .arg(&socket)
        .arg("--filter")
        .args(talk.iter().map(|n| format!("--talk={n}")))
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::null())
        .kill_on_drop(true);
    inherit(&mut command, vec![write.as_raw_fd()]);
    let child = command.spawn().context("start xdg-dbus-proxy (install xdg-dbus-proxy)")?;
    drop(write);
    // It writes a byte once the socket is listening.
    let raw = read.as_raw_fd();
    let ready = tokio::task::spawn_blocking(move || {
        let mut poll = libc::pollfd { fd: raw, events: libc::POLLIN, revents: 0 };
        let mut byte = 0u8;
        unsafe { libc::poll(&mut poll, 1, 5000) == 1 && libc::read(raw, (&mut byte as *mut u8).cast(), 1) == 1 }
    })
    .await?;
    anyhow::ensure!(ready, "xdg-dbus-proxy didn't start");
    Ok((child, socket, read))
}

fn pipe() -> Result<(OwnedFd, OwnedFd)> {
    let mut fds = [0; 2];
    anyhow::ensure!(unsafe { libc::pipe2(fds.as_mut_ptr(), libc::O_CLOEXEC) } == 0, "pipe: {}", std::io::Error::last_os_error());
    Ok(unsafe { (OwnedFd::from_raw_fd(fds[0]), OwnedFd::from_raw_fd(fds[1])) })
}

/// The seccomp program in a fresh sealed-off memfd, positioned at its start, for bwrap's
/// `--seccomp`.
pub fn seccomp_fd() -> Result<OwnedFd> {
    let program = seccomp_program();
    let fd = unsafe { libc::memfd_create(c"nixe-assistant-seccomp".as_ptr(), libc::MFD_CLOEXEC) };
    anyhow::ensure!(fd >= 0, "memfd: {}", std::io::Error::last_os_error());
    let fd = unsafe { OwnedFd::from_raw_fd(fd) };
    let mut file = std::fs::File::from(fd);
    std::io::Write::write_all(&mut file, &program)?;
    std::io::Seek::seek(&mut file, std::io::SeekFrom::Start(0))?;
    Ok(file.into())
}

