    #[test]
    fn the_seccomp_program_is_well_formed() {
        let p = seccomp_program();
        assert_eq!(p.len() % 8, 0);
        let n = p.len() / 8;
        assert!(n < 255);
        // Every jump lands inside the program.
        for i in 0..n {
            let (code, jt, jf) = (u16::from_ne_bytes([p[i * 8], p[i * 8 + 1]]), p[i * 8 + 2] as usize, p[i * 8 + 3] as usize);
            if code & 0x07 == 0x05 {
                assert!(i + 1 + jt.max(jf) < n, "jump out of range at {i}");
            }
        }
        // The last instruction allows.
        assert_eq!(u32::from_ne_bytes(p[p.len() - 4..].try_into().unwrap()), RET_ALLOW);
    }

    fn bwrap() -> bool {
        std::process::Command::new("bwrap").args(["--ro-bind", "/", "/", "true"]).status().is_ok_and(|s| s.success())
    }

    /// Runs `script` with sh in a strict sandbox under the seccomp filter; its exit status.
    async fn sandboxed(profile: SandboxProfile, script: &str) -> Option<i32> {
        if !bwrap() {
            return None;
        }
        let dir = tempfile::tempdir().unwrap();
        let (package, data) = (dir.path().join("pkg"), dir.path().join("data"));
        std::fs::create_dir_all(&package).unwrap();
        std::fs::create_dir_all(&data).unwrap();
        let env = HashMap::new();
        let args = vec!["-c".to_string(), script.to_string()];
        let launch = Launch { id: "test", executable: "sh", args: &args, env: &env, package: &package, data: &data, first_party: false };
        let home = crate::fs::home().unwrap();
        let mut argv = vec!["bwrap".to_string()];
        argv.extend(bwrap_args(&profile, &launch, &home, None, None).unwrap());
        let seccomp = seccomp_fd().unwrap();
        argv.extend(["--seccomp".into(), seccomp.as_raw_fd().to_string(), "--".into(), "sh".into(), "-c".into(), script.into()]);
        let mut command = tokio::process::Command::new(&argv[0]);
        command.args(&argv[1..]);
        inherit(&mut command, vec![seccomp.as_raw_fd()]);
        let status = command.status().await.unwrap();
        status.code()
    }

    #[tokio::test]
    async fn a_strict_sandbox_runs_and_confines() {
        let home = crate::fs::home().unwrap();
        let script = format!("test ! -e {}/.bashrc && echo ok > /tmp/x && cat /tmp/x >/dev/null", home.display());
        let Some(code) = sandboxed(SandboxProfile::default(), &script).await else { return };
        assert_eq!(code, 0, "home is empty and /tmp writable");
        // New namespaces are refused inside (unshare(1) uses unshare(2)).
        if std::process::Command::new("unshare").arg("--version").output().is_ok() {
            let code = sandboxed(SandboxProfile::default(), "unshare -r true").await.unwrap();
            assert_ne!(code, 0, "unshare must fail under the filter");
        }
    }

